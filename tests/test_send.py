def lane(name, ext, material, colour, tool, filled=True):
    return {"name": name, "unit": "A", "extruder": ext, "map": ["T%d" % tool], "material": material,
            "color": colour, "prep": filled, "load": filled, "tool_loaded": False}


class Fake(http.server.BaseHTTPRequestHandler):
    state = {}

    def log_message(self, *args):
        pass

    def _reply(self, value, code=200):
        data = json.dumps({"result": value} if code == 200 else {"error": {"message": value}}).encode()
        self.send_response(code)
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self):
        s = Fake.state
        s.setdefault("keys", []).append(self.headers.get("X-Api-Key"))
        parts = urllib.parse.urlsplit(self.path)
        if parts.path == "/printer/objects/list":
            self._reply({"objects": list(s["objects"])})
        elif parts.path == "/printer/objects/query":
            names = [urllib.parse.unquote(p) for p in parts.query.split("&")]
            self._reply({"status": {n: s["objects"][n] for n in names if n in s["objects"]}})
        elif parts.path == "/server/config":
            self._reply({"config": {"file_manager": {"queue_gcode_uploads": s.get("queue_uploads", False)}}})
        elif parts.path == "/machine/timelapse/settings":
            self._reply(s["timelapse"]) if s["timelapse"] else self._reply("none", 404)
        else:
            self._reply("nope", 404)

    def do_POST(self):
        s = Fake.state
        body = self.rfile.read(int(self.headers.get("Content-Length", 0))).decode()
        parts = urllib.parse.urlsplit(self.path)
        if parts.path == "/printer/gcode/script":
            script = json.loads(body)["script"]
            s["scripts"].append(script)
            if s.get("ignore_map"):
                return self._reply("ok")
            for line in script.split("\n"):
                m = re.match(r"SET_MAP LANE=(\w+) MAP=(T\d)", line)
                target = s["objects"]["AFC_lane " + m.group(1)]
                for other in [v for k, v in s["objects"].items() if k.startswith("AFC_lane ")]:
                    if m.group(2) in other["map"]:
                        other["map"] = target["map"]
                target["map"] = [m.group(2)]
            self._reply("ok")
        elif parts.path == "/machine/timelapse/settings":
            s["timelapse_posts"].append(parts.query)
            self._reply({})


def reset():
    Fake.state = {
        "objects": {
            "webhooks": {"state": "ready"}, "print_stats": {"state": "standby"},
            "idle_timeout": {"state": "Idle"},
            "AFC": {"lanes": ["lane1", "lane2", "lane3", "lane4"], "error_state": False,
                    "bypass_state": False, "multiple_tool_mapping": False},
            "AFC_lane lane1": lane("lane1", "extruder0", "PLA", "#FF0000", 0),
            "AFC_lane lane2": lane("lane2", "extruder1", "PLA+", "#0000FF", 1),
            "AFC_lane lane3": lane("lane3", "extruder2", "PETG", "#00FF00", 2),
            "AFC_lane lane4": lane("lane4", "extruder3", "ABS", "#000000", 3, filled=False),
            "output_pin purge": {"value": 1.0}, "output_pin flow_calibration": {"value": 0.0},
            "output_pin purge_line": {"value": 1.0}, "output_pin bed_leveling": {"value": 1.0},
        },
        "timelapse": {"enabled": False, "mode": "layermacro"},
        "scripts": [], "timelapse_posts": [],
    }


def job_file(text=HEADER + FOOTER):
    handle, path = tempfile.mkstemp(suffix=".gcode")
    with os.fdopen(handle, "w", newline="") as out:
        out.write(text)
    return path


def contents(path):
    with open(path, newline="") as source:
        return source.read()


def check_command_matches_firmware(firmware):
    source = open(firmware, encoding="utf-8").read()
    code = source[source.index("def creator5_start_command"):source.index("def creator5_slicer_z_offset")]
    scope = {"re": re}
    exec(code, scope)
    padding = "; pad\n" * 12000
    for header, footer in [(HEADER, FOOTER), ("T2\nM104 S200\n", ""), ("AFC_SELECT_TOOL TOOL=extruder3\nM109 S210\nM191 S50\n", FOOTER),
                           ((HEADER + padding)[:65536], FOOTER), ("M109 S230\n; filament_type = pla;bad value;'petg'\n", "")]:
        assert send.start_command(header, footer) == scope["creator5_start_command"](header, footer), (header[:40], footer[:40])
    print("generated command matches the firmware's")


def check_job():
    path = job_file()
    job = send.read_job(path, "x.gcode")
    assert [t["tool"] for t in job["tools"]] == [1, 2]
    assert job["tools"][0]["material"] == "PETG" and job["tools"][1]["material"] == '"PLA+"'.strip('"')
    assert job["tools"][0]["grams"] == 3.5 and job["time"] == "1h 2m" and job["thumbnail"] == "AAAA"
    assert not job["has_frames"] and job["layer_marks"] == 2
    os.remove(path)
    print("job read")


def check_flow(url):
    client = send.Moonraker(url, "secret")

    # nothing changed: the file and printer stay untouched
    reset()
    path = job_file()
    job = send.read_job(path)
    snap = client.snapshot()
    assert snap.switches == {"flow_calibration": False, "purge": True, "purge_line": True, "bed_leveling": True}
    same = {"mapping": snap.current_mapping(job["tools"]),
            "options": {"flow_calibration": False, "purge": True, "purge_line": True, "bed_leveling": True, "buildplate_check": True},
            "timelapse": False}
    send.apply_setup(client, job, path, same)
    assert contents(path) == HEADER + FOOTER and not Fake.state["scripts"] and not Fake.state["timelapse_posts"]
    assert set(Fake.state["keys"]) == {"secret"}

    # options for this print, timelapse added, a swap of lanes
    request = {"mapping": {"1": "lane3", "2": "lane2"},
               "options": {"flow_calibration": True, "purge": False, "purge_line": True, "bed_leveling": True, "buildplate_check": False},
               "timelapse": True}
    send.apply_setup(client, job, path, request)
    text = contents(path)
    lines = text.split("\n")
    assert lines[0] == send.NOTE and lines[1].startswith("C5_PRINT_START TOOL=1 HOTEND=240 BED=60")
    for part in ("FLOW_CALIBRATION=1", "PURGE=0", "BUILDPLATE_CHECK=0", "USED_TOOLS=1,2", "MATERIAL1=PETG"):
        assert part in lines[1], part
    assert "PURGE_LINE" not in lines[1] and "BED_LEVELING" not in lines[1]
    assert text.count(send.FRAME_COMMAND + "\n;LAYER_CHANGE") == 2
    assert Fake.state["timelapse_posts"] == ["enabled=True&mode=layermacro"]
    assert Fake.state["objects"]["AFC_lane lane3"]["map"] == ["T1"] and Fake.state["objects"]["AFC_lane lane2"]["map"] == ["T2"]
    # switches on the printer were left alone
    assert not any("SET_PIN" in s for s in Fake.state["scripts"])
    os.remove(path)

    # an explicit start line gets the parameters, frames come out
    reset()
    framed = "C5_PRINT_START TOOL=0 BED=60 HOTEND=220 PURGE=1\n;LAYER_CHANGE\nTIMELAPSE_TAKE_FRAME\nG1 Z1\n" + FOOTER
    path = job_file(framed)
    job = send.read_job(path)
    assert job["has_frames"]
    send.apply_setup(client, job, path, {"mapping": client.snapshot().current_mapping(job["tools"]), "options": {"purge": False}, "timelapse": False})
    text = contents(path)
    assert text.startswith("C5_PRINT_START TOOL=0 BED=60 HOTEND=220 PURGE=0\n") and send.FRAME_COMMAND not in text
    os.remove(path)

    # CRLF stays CRLF
    reset()
    path = job_file((HEADER + FOOTER).replace("\n", "\r\n"))
    job = send.read_job(path)
    send.apply_setup(client, job, path, {"mapping": client.snapshot().current_mapping(job["tools"]), "options": {}, "timelapse": True})
    assert (send.FRAME_COMMAND + "\r\n;LAYER_CHANGE\r\n") in contents(path)
    os.remove(path)

    # refused: file and printer untouched
    for name, change, request_map in [
        ("printing", lambda o: o["print_stats"].update(state="printing"), None),
        ("paused", lambda o: o["print_stats"].update(state="paused"), None),
        ("macro running", lambda o: o["idle_timeout"].update(state="Printing"), None),
        ("afc error", lambda o: o["AFC"].update(error_state=True), None),
        ("empty lane", lambda o: None, {"1": "lane4", "2": "lane2"}),
        ("shared lane", lambda o: None, {"1": "lane2", "2": "lane2"}),
    ]:
        reset()
        path = job_file()
        job = send.read_job(path)
        change(Fake.state["objects"])
        mapping = request_map or {"1": "lane2", "2": "lane3"}
        try:
            send.apply_setup(client, job, path, {"mapping": mapping, "options": {"purge": False}, "timelapse": True})
            raise AssertionError("not refused: " + name)
        except send.SetupError:
            pass
        assert contents(path) == HEADER + FOOTER and not Fake.state["scripts"], name
        os.remove(path)

    # the printer ignores SET_MAP: reported, and the file isn't changed
    reset()
    Fake.state["ignore_map"] = True
    path = job_file()
    job = send.read_job(path)
    try:
        send.apply_setup(client, job, path, {"mapping": {"1": "lane3", "2": "lane2"}, "options": {"purge": False}})
        raise AssertionError("not noticed")
    except send.SetupError as error:
        assert "mapping" in str(error)
    assert contents(path) == HEADER + FOOTER
    os.remove(path)

    # auto match: material first, then colour, and never an empty lane
    reset()
    path = job_file()
    job = send.read_job(path)
    assert client.snapshot().auto_mapping(job["tools"]) == {"1": "lane3", "2": "lane2"}
    os.remove(path)

    # no timelapse on the printer, no AFC
    reset()
    Fake.state["timelapse"] = None
    del Fake.state["objects"]["AFC"]
    snap = client.snapshot()
    assert not snap.afc and snap.timelapse is None and send.view_state(snap, {"tools": [], "has_frames": False})["timelapse"] is None
    print("apply flow passed")


def check_session(url):
    reset()
    posts = []

    class Window:
        def post(self, payload):
            posts.append(payload)

    path = job_file()
    session = send.SetupSession(send.Moonraker(url), send.read_job(path), path)
    session.window = Window()
    session._work({"action": "read"})
    assert posts[-1]["kind"] == "state" and posts[-1]["mapping"] == {"1": "lane3", "2": "lane2"}
    assert [o["id"] for o in posts[-1]["options"]] == ["flow_calibration", "purge", "purge_line", "bed_leveling"]
    assert {o["group"] for o in posts[-1]["options"]} == {"Calibration", "Purge"}
    assert all(isinstance(o["printer_on"], bool) and "on" in o for o in posts[-1]["options"])
    assert posts[-1]["current"] == {"1": "lane2", "2": "lane3"}
    Fake.state["objects"]["print_stats"]["state"] = "printing"
    session._work({"action": "apply", "mapping": {"1": "lane2", "2": "lane3"}, "options": {}})
    assert posts[-1]["kind"] == "error" and not session.done.is_set()
    Fake.state["objects"]["print_stats"]["state"] = "standby"
    session._work({"action": "apply", "mapping": {"1": "lane2", "2": "lane3"}, "options": {}})
    assert session.done.is_set() and session.result == "continue"
    # sending unchanged is always allowed; the window says whether Moonraker will queue it
    for state, queue_on in (("standby", False), ("printing", True), ("paused", False)):
        Fake.state["objects"]["print_stats"]["state"] = state
        Fake.state["queue_uploads"] = queue_on
        session = send.SetupSession(send.Moonraker(url), send.read_job(path), path)
        session.window = Window()
        session._work({"action": "read"})
        assert posts[-1]["printing"] is (state != "standby") and posts[-1]["queue_uploads"] is queue_on
        session.on_message({"action": "skip"})
        assert session.done.is_set() and session.result == "continue", state
    Fake.state["objects"]["print_stats"]["state"] = "standby"
    session = send.SetupSession(send.Moonraker(url), send.read_job(path), path)
    session.on_message({"action": "cancel"})
    assert session.done.is_set() and session.result == "cancel"
    assert "</script>" not in send.page_html({"name": "</script>", "tools": []}).split("const job=")[1].split(";const")[0]
    os.remove(path)
    print("window session passed")


def check_prefs():
    send.prefs_path = lambda: os.path.join(tempfile.mkdtemp(), "prefs.json")
    assert send.load_prefs() == {}
    path = tempfile.mkdtemp()
    send.prefs_path = lambda: os.path.join(path, "prefs.json")
    send.save_prefs({"purge": True, "bed_leveling": False, "junk": 3}, True)
    assert send.load_prefs() == {"purge": True, "bed_leveling": False, "timelapse": True}
    open(send.prefs_path(), "w").write("not json")
    assert send.load_prefs() == {}
    lane = lambda name, colour, maps, filled=True: {"name": name, "filled": filled, "material": "PLA", "colour": colour, "maps": maps}
    printer = send.Printer(afc=True, lanes=[lane("A", "#ff0000", ["T1"]), lane("B", "#0000ff", ["T0"])])
    tools = [{"tool": 0, "material": "PLA", "colour": "#ff0000"}, {"tool": 1, "material": "PLA", "colour": "#0000ff"}]
    assert printer.auto_mapping(tools) == {"0": "A", "1": "B"}
    assert printer.initial_mapping(tools) == {"0": "A", "1": "B"}
    # a lane that holds one tool swaps with the other
    assert printer.plan_mapping(tools, {"0": "A", "1": "B"}) == (["SET_MAP LANE=A MAP=T0"], [])
    assert printer.plan_mapping(tools, {"0": "B", "1": "A"}) == ([], [])
    assert printer.plan_mapping(tools, {"0": "A", "1": "A"})[1] == ["A can't feed both T0 and T1."]
    printer.share = True
    assert printer.plan_mapping(tools, {"0": "A", "1": "A"})[0] == ["SET_MAP LANE=A MAP=T0"]
    printer.share = False
    printer.lanes[1]["filled"] = False
    assert printer.initial_mapping(tools) == printer.current_mapping(tools)
    unset = send.Printer(afc=True, lanes=[{"name": "extruder0", "filled": True, "material": "", "colour": "", "maps": ["T0"]},
                                          {"name": "extruder1", "filled": True, "material": "", "colour": "", "maps": ["T1"]}])
    assert unset.auto_mapping([{"tool": 1, "material": "PETG", "colour": "#000000"}]) == {"1": "extruder1"}
    assert send.Printer().blocked() == ""
    assert send.Printer(klippy="shutdown").blocked() == "Klipper isn't ready."
    assert send.Printer(state="printing").blocked() == "The printer is busy."
    assert send.Printer(busy=True).printing()
    assert send.Printer(afc_error=True).blocked().startswith("AFC has an error")
    print("prefs passed")


def check_plan():
    lane = lambda name, colour, maps: {"name": name, "filled": True, "material": "PLA", "colour": colour, "maps": maps}
    tools = [{"tool": 0, "material": "PLA", "colour": "#ff0000"}, {"tool": 1, "material": "PLA", "colour": "#0000ff"}]
    job = {"tools": tools, "has_frames": False, "layer_marks": 2}
    printer = send.Printer(afc=True, lanes=[lane("A", "#ff0000", ["T1"]), lane("B", "#0000ff", ["T0"])],
                           switches={"purge": True}, timelapse={"enabled": False, "mode": "layermacro"})
    keep = {"mapping": {"0": "B", "1": "A"}}

    def plan(request, job=job, printer=printer):
        return send.plan_setup(printer, job, request)

    def fails(request, text, job=job, printer=printer):
        try:
            send.plan_setup(printer, job, request)
        except send.SetupError as error:
            assert text in str(error), str(error)
        else:
            raise AssertionError("expected SetupError")

    assert plan(keep) == ([], {}, None, False)
    fails(keep, "busy", printer=send.Printer(state="printing"))
    fails({"mapping": {"0": "A", "1": "A"}}, "can't feed both")
    # overrides only where the request differs from the switches
    assert plan({**keep, "options": {"purge": True, "buildplate_check": True}})[1] == {}
    assert plan({**keep, "options": {"purge": False, "buildplate_check": False}})[1] == {"PURGE": 0, "BUILDPLATE_CHECK": 0}
    # timelapse: add, remove, leave, and no layer marks
    assert plan({**keep, "timelapse": True}) == ([], {}, True, True)
    assert plan({**keep, "timelapse": False})[2] is None
    assert plan({**keep}, printer=send.Printer(afc=True, lanes=printer.lanes))[2] is None
    framed = dict(job, has_frames=True)
    assert plan({**keep, "timelapse": False}, job=framed)[2] is False
    assert plan({**keep, "timelapse": True}, job=framed)[2] is None
    on = send.Printer(afc=True, lanes=printer.lanes, timelapse={"enabled": True, "mode": "layermacro"})
    assert plan({**keep, "timelapse": True}, printer=on)[3] is False
    fails({**keep, "timelapse": True}, "no layer change markers", job=dict(job, layer_marks=0))
    bare = send.Printer(afc=True, lanes=printer.lanes)
    assert plan({**keep, "timelapse": True}, job=dict(job, layer_marks=0), printer=bare)[2] is None
    print("plan passed")


def check_spellings():
    for spelling in ("LAYER_CHANGE", "CHANGE_LAYER"):
        handle, path = tempfile.mkstemp(suffix=".gcode")
        os.write(handle, ("M190 S60\n;%s\nG1 Z1\n;%s\nG1 Z2\n" % (spelling, spelling)).encode())
        os.close(handle)
        job = send.read_job(path)
        assert job["layer_spelling"] == spelling and job["layer_marks"] == 2
        out = path + ".out"
        send.rewrite_job(path, out, job, None, True)
        assert contents(out).count(send.FRAME_COMMAND + "\n;" + spelling) == 2
        os.remove(path)
        os.remove(out)
    handle, path = tempfile.mkstemp(suffix=".gcode")
    os.write(handle, b"M190 S60\n;LAYER_CHANGE\nG1 Z1\n;CHANGE_LAYER\nG1 Z2\n")
    os.close(handle)
    job = send.read_job(path)
    assert job["layer_spelling"] == "LAYER_CHANGE"
    out = path + ".out"
    send.rewrite_job(path, out, job, None, True)
    assert contents(out).count(send.FRAME_COMMAND + "\n;LAYER_CHANGE") == 1
    os.remove(path)
    os.remove(out)
    print("spellings passed")


def main():
    prefs_dir = tempfile.mkdtemp()
    send.prefs_path = lambda: os.path.join(prefs_dir, "prefs.json")
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), Fake)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    url = "http://127.0.0.1:%d" % server.server_address[1]
    if len(sys.argv) > 1:
        check_command_matches_firmware(sys.argv[1])
    check_job()
    check_flow(url)
    check_prefs()
    check_plan()
    check_spellings()
    check_session(url)
    assert send.printer_address(lambda k: {"print_host": "192.168.2.92", "printhost_port": "7125"}.get(k)) == "http://192.168.2.92:7125"
    assert send.is_creator5(lambda k: "Flashforge Creator 5 Pro" if k == "printer_model" else None)
    assert not send.is_creator5(lambda k: "Snapmaker U1" if k == "printer_model" else None)
    print("all passed")


main()
